export function reliabilityText(language: 'en' | 'de', key: ReliabilityKey, values: Record<string, string | number> = {}) {
  return (language === 'de' ? de : en)[key].replace(/\{(\w+)\}/g, (_match, name: string) => {
    if (!(name in values)) throw new Error(`Missing reliability translation value: ${name}`)
    return typeof values[name] === 'number' ? new Intl.NumberFormat(language).format(values[name]) : values[name]
  })
}
export type { ReliabilityKey }
