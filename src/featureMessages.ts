export function featureText(language: 'en' | 'de', key: FeatureKey, values: Record<string, string | number> = {}) {
  const template = (language === 'de' ? de : en)[key]
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    if (!(name in values)) throw new Error(`Missing feature translation value: ${name}`)
    return typeof values[name] === 'number' ? new Intl.NumberFormat(language).format(values[name]) : values[name]
  })
}
